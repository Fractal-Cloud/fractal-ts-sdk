/**
 * The offer contract generator (scripts/offer-contracts/), on a fixture pair
 * of published contracts, and the committed generated sources against the
 * committed snapshot.
 */
import {readFileSync, readdirSync} from 'node:fs';
import {describe, expect, it} from 'vitest';
import prettier from 'prettier';
import {
  buildModel,
  canonicalJson,
  contractIdentifier,
  domainModule,
  formatModules,
  renderModules,
} from '../../../../scripts/offer-contracts/generator.mjs';
import {
  GENERATED_DIR,
  generateFromSnapshot,
  readSnapshot,
} from '../../../../scripts/offer-contracts/snapshot.mjs';
import {contractKey} from './contract_key';
import {contractKeys} from './contract_keys';
import {contractValueProblem} from './contract_value_problem';
import type {OfferContract} from './offer_contract';
import {toContractKeys} from '../neutral_rules';
import {NetworkAndCompute_IaaS_AwsLb} from '../generated/network_and_compute';

const fixture = (name: string) =>
  JSON.parse(
    readFileSync(`src/model/offers/contract/fixtures/${name}.json`, 'utf8'),
  );

const generate = async (projections: unknown[]) => {
  const options = (await prettier.resolveConfig('src/model/x.ts')) ?? {};
  return formatModules(
    renderModules(buildModel(projections)),
    prettier,
    options,
  );
};

describe('generator', () => {
  it('renders one module per domain and one contract per offer type', async () => {
    const files = await generate([fixture('java-agent'), fixture('go-agent')]);
    expect([...files.keys()]).toEqual([
      'messaging.ts',
      'network_and_compute.ts',
    ]);
    expect(files.get('network_and_compute.ts')).toMatchInlineSnapshot(`
      "// GENERATED by scripts/generate-offer-contracts.mjs from contracts/snapshot.
      // Do not edit: refresh the snapshot (npm run contracts:refresh) and regenerate
      // (npm run contracts:generate). See docs/offer-contracts.md.
      import type {OfferContract} from '../contract/offer_contract';

      export const NetworkAndCompute_IaaS_AwsLb = {
        offerType: 'NetworkAndCompute.IaaS.AwsLb',
        serviceTypes: ['NetworkAndCompute.IaaS.LoadBalancer'],
        declaredBy: [
          {
            agentId: 'fractal-cloud-agent-aws',
            agentVersion: 'v1.2.3',
            contractSchemaVersion: '2.0',
            provider: 'AWS',
            parameterRules: [{id: 'r1', kind: 'anyOf', keys: ['lbScheme', 'lbType']}],
          },
        ],
        params: {
          lbScheme: {
            type: 'string',
            required: false,
            default: 'internal',
            values: ['internal', 'internet-facing'],
          },
          lbType: {
            type: 'string',
            required: false,
            values: ['application', 'network'],
            valuesLevel: 'warn',
          },
          tags: {
            type: 'object',
            required: false,
            aliases: [{key: 'labels', deprecated: true}],
          },
        },
      } as const satisfies OfferContract;
      "
    `);
  });

  it('merges an offer several agents declare', () => {
    const [kafka] = buildModel([fixture('go-agent'), fixture('java-agent')]);
    expect(kafka.offerType).toBe('Messaging.CaaS.Kafka');
    expect(kafka.declaredBy.map((d: {agentId: string}) => d.agentId)).toEqual([
      'aria-agent-caas-k8s',
      'fractal-cloud-agent-aws',
    ]);
    expect([...kafka.serviceTypes].sort()).toEqual([
      'Messaging.CaaS.Kafka',
      'Messaging.CaaS.Streaming',
    ]);
    const params = Object.fromEntries(kafka.params);
    // integer and number meet at number; differing defaults are dropped.
    expect(params.replicas).toEqual({
      type: 'number',
      required: false,
      agents: ['aria-agent-caas-k8s', 'fractal-cloud-agent-aws'],
    });
    // Required by one agent, not read by the other: whichever agent reconciles
    // the component, a key is required only when that agent requires it, so the
    // merged contract does not require it of everyone, and records who does.
    expect(params.storageSize.required).toBe(false);
    expect(params.storageSize.requiredBy).toEqual(['fractal-cloud-agent-aws']);
    expect(params.storageSize.agents).toEqual(['fractal-cloud-agent-aws']);
    expect(params.namespace.default).toBe('kafka');
  });

  it('records which agents read a key only when not all of them do', async () => {
    const files = await generate([fixture('java-agent'), fixture('go-agent')]);
    const text = files.get('messaging.ts')!;
    expect(text).toContain("agents: ['aria-agent-caas-k8s'],");
    expect(text).toContain('/** Broker volume size, e.g. 100Gi. */');
    expect(text).not.toMatch(/replicas: \{[^}]*agents/);
  });

  it('intersects the vocabularies of agents that both constrain a key', () => {
    const a = {
      schemaVersion: '2.0',
      agentId: 'a',
      agentVersion: 'v1',
      offers: [
        {
          offerType: 'X.CaaS.Y',
          provider: 'CaaS',
          params: [{key: 'k', type: 'string', values: ['p', 'q']}],
        },
      ],
    };
    const b = {
      ...a,
      agentId: 'b',
      offers: [
        {
          offerType: 'X.CaaS.Y',
          provider: 'CaaS',
          params: [{key: 'k', type: 'string', values: ['q', 'r']}],
        },
      ],
    };
    const [offer] = buildModel([a, b]);
    expect(offer.params.get('k').values).toEqual(['q']);
  });

  const twoAgents = (
    first: Record<string, unknown>,
    second: Record<string, unknown>,
  ) => {
    const a = {
      schemaVersion: '2.0',
      agentId: 'a',
      agentVersion: 'v1',
      offers: [
        {
          offerType: 'X.CaaS.Y',
          provider: 'CaaS',
          params: [{key: 'k', type: 'string', ...first}],
        },
      ],
    };
    const b = {
      ...a,
      agentId: 'b',
      offers: [
        {
          offerType: 'X.CaaS.Y',
          provider: 'CaaS',
          params: [{key: 'k', type: 'string', ...second}],
        },
      ],
    };
    return [a, b];
  };

  it('requires a key only when every agent declaring the offer requires it', () => {
    for (const [first, second, required, requiredBy] of [
      [{required: true}, {required: true}, true, undefined],
      [{required: true}, {required: false}, false, ['a']],
      [{required: false}, {required: true}, false, ['b']],
      [{}, {required: true}, false, ['b']],
      [{}, {}, false, undefined],
    ] as const) {
      // whatever order the agents come in
      for (const projections of [
        twoAgents(first, second),
        twoAgents(first, second).reverse(),
      ]) {
        const [offer] = buildModel(projections);
        expect(offer.params.get('k').required).toBe(required);
        expect(offer.params.get('k').requiredBy).toEqual(requiredBy);
      }
    }
  });

  it('does not require a key that another agent declaring the offer does not read', () => {
    const [a, b] = twoAgents({required: true}, {});
    const notK = {
      ...b,
      offers: [{...b.offers[0], params: [{key: 'other', type: 'string'}]}],
    };
    for (const projections of [
      [a, notK],
      [notK, a],
    ]) {
      const [offer] = buildModel(projections);
      expect(offer.params.get('k')).toMatchObject({
        required: false,
        requiredBy: ['a'],
        agents: ['a'],
      });
    }
    // Declared by one agent only, it stays as that agent says.
    const [single] = buildModel([a]);
    expect(single.params.get('k').required).toBe(true);
    expect(single.params.get('k').requiredBy).toBeUndefined();
  });

  it('renders requiredBy next to agents', async () => {
    const files = await generate([fixture('java-agent'), fixture('go-agent')]);
    expect(files.get('messaging.ts')).toMatch(
      /storageSize: \{\s*type: 'string',\s*required: false,\s*agents: \['fractal-cloud-agent-aws'\],\s*requiredBy: \['fractal-cloud-agent-aws'\],\s*\}/,
    );
  });

  it('refuses agents whose vocabularies share no value', () => {
    expect(() =>
      buildModel(twoAgents({values: ['p', 'q']}, {values: ['r', 's']})),
    ).toThrow(
      "X.CaaS.Y.k takes p, q for a and r, s for b: no value satisfies every agent",
    );
  });

  it('keeps a key sensitive when any agent marks it so', () => {
    for (const [first, second] of [
      [{sensitive: false}, {sensitive: true}],
      [{sensitive: true}, {sensitive: false}],
      [{}, {sensitive: true}],
      [{sensitive: true}, {}],
    ]) {
      const [offer] = buildModel(twoAgents(first, second));
      expect(offer.params.get('k').sensitive).toBe(true);
    }
  });

  it('refuses agents that disagree on what a key is', () => {
    const go = fixture('go-agent');
    go.offers[0].params.push({key: 'storageSize', type: 'integer'});
    expect(() => buildModel([fixture('java-agent'), go])).toThrow(
      /Messaging\.CaaS\.Kafka\.storageSize is 'integer' for aria-agent-caas-k8s and 'string' for fractal-cloud-agent-aws/,
    );
  });

  it('refuses what it cannot read', () => {
    expect(() =>
      buildModel([{...fixture('go-agent'), schemaVersion: '3.0'}]),
    ).toThrow(/unsupported projection schemaVersion '3.0'/);
    expect(() => buildModel([{...fixture('go-agent'), agentId: 1}])).toThrow(
      /without agentId/,
    );
    expect(() => buildModel([{...fixture('go-agent'), offers: {}}])).toThrow(
      /offers is not a list/,
    );
    const badType = fixture('go-agent');
    badType.offers[0].params[0].type = 'text';
    expect(() => buildModel([badType])).toThrow(
      /not a contract value type/,
    );
    const badOffer = fixture('go-agent');
    badOffer.offers[0].offerType = 'Kafka';
    expect(() => buildModel([badOffer])).toThrow(/is not an offer type/);
    const twice = fixture('go-agent');
    twice.offers.push(twice.offers[0]);
    expect(() => buildModel([twice])).toThrow(
      /declares Messaging.CaaS.Kafka twice/,
    );
  });

  describe('key aliases (contracts/key-aliases.json)', () => {
    const projection = (
      params: ReadonlyArray<Record<string, unknown>>,
    ): Record<string, unknown> => ({
      schemaVersion: '2.0',
      agentId: 'a',
      agentVersion: 'v1',
      offers: [{offerType: 'X.PaaS.Y', provider: 'AWS', params}],
    });
    const declaredTwice = projection([
      {key: 'versioning', type: 'boolean', default: false},
      {key: 'versioningEnabled', type: 'boolean', default: false},
    ]);
    const alias = {
      offerType: 'X.PaaS.Y',
      key: 'versioning',
      alias: 'versioningEnabled',
    };

    it('turns an older spelling into a deprecated alias of the canonical key', () => {
      const [offer] = buildModel([declaredTwice], [alias]);
      expect([...offer.params.keys()]).toEqual(['versioning']);
      expect(offer.params.get('versioning').aliases).toEqual([
        {deprecated: true, key: 'versioningEnabled'},
      ]);
    });

    it('keeps aliases the agent already declares', () => {
      const [offer] = buildModel(
        [
          projection([
            {
              key: 'versioning',
              type: 'boolean',
              aliases: [{key: 'old', deprecated: true}],
            },
            {key: 'versioningEnabled', type: 'boolean'},
          ]),
        ],
        [alias],
      );
      expect(offer.params.get('versioning').aliases).toEqual([
        {key: 'old', deprecated: true},
        {deprecated: true, key: 'versioningEnabled'},
      ]);
    });

    it('fails once the agent no longer declares both keys, so the entry is removed', () => {
      expect(() =>
        buildModel(
          [projection([{key: 'versioning', type: 'boolean'}])],
          [alias],
        ),
      ).toThrow(
        /key-aliases\.json: X\.PaaS\.Y declares no 'versioningEnabled'; remove the entry/,
      );
      expect(() =>
        buildModel(
          [projection([{key: 'versioningEnabled', type: 'boolean'}])],
          [alias],
        ),
      ).toThrow(/X\.PaaS\.Y declares no 'versioning'/);
      expect(() =>
        buildModel([declaredTwice], [{...alias, offerType: 'X.PaaS.Z'}]),
      ).toThrow(/X\.PaaS\.Z is declared by no agent/);
    });

    it('refuses an alias of another type', () => {
      expect(() =>
        buildModel(
          [
            projection([
              {key: 'versioning', type: 'boolean'},
              {key: 'versioningEnabled', type: 'string'},
            ]),
          ],
          [alias],
        ),
      ).toThrow(/'versioningEnabled' is 'string', 'versioning' is 'boolean'/);
    });
  });

  it('names modules and constants after the offer type', () => {
    expect(contractIdentifier('NetworkAndCompute.IaaS.AwsLb')).toBe(
      'NetworkAndCompute_IaaS_AwsLb',
    );
    expect(domainModule('APIManagement.CaaS.Traefik')).toBe('api_management');
    expect(domainModule('BigData.PaaS.AwsDatabricks')).toBe('big_data');
    expect(domainModule('AI.SaaS.Unmanaged')).toBe('ai');
  });

  it('writes one canonical text per document', () => {
    expect(canonicalJson({b: 1, a: [{d: 1, c: 2}]})).toBe(
      '{\n  "a": [\n    {\n      "c": 2,\n      "d": 1\n    }\n  ],\n  "b": 1\n}\n',
    );
  });
});

describe('the committed contracts', () => {
  it('are generated from the committed snapshot, untouched', async () => {
    const files = await generateFromSnapshot('.');
    expect(readdirSync(GENERATED_DIR).sort()).toEqual([...files.keys()].sort());
    for (const [name, text] of files) {
      expect(readFileSync(`${GENERATED_DIR}/${name}`, 'utf8'), name).toBe(text);
    }
  });

  it('come from the agent releases contracts/sources.json pins', () => {
    const projections = readSnapshot('.');
    expect(projections.map((p: {agentId: string}) => p.agentId)).toContain(
      'fractal-cloud-agent-aws',
    );
  });
});

describe('contract keys', () => {
  it('names a declared key', () => {
    expect(contractKey(NetworkAndCompute_IaaS_AwsLb, 'lbScheme')).toBe(
      'lbScheme',
    );
    expect(contractKeys(NetworkAndCompute_IaaS_AwsLb).lbType).toBe('lbType');
  });

  it('refuses a translation that writes a key it did not name', () => {
    const rule = toContractKeys(NetworkAndCompute_IaaS_AwsLb, ['lbType'], () => ({
      lbScheme: 'internal',
    }));
    expect(() =>
      rule.kind === 'translate' ? rule.apply('x') : undefined,
    ).toThrow(
      "NetworkAndCompute.IaaS.AwsLb: a neutral translation wrote 'lbScheme', not one of lbType.",
    );
  });

  it('refuses a key the contract does not declare', () => {
    expect(() =>
      contractKey(NetworkAndCompute_IaaS_AwsLb, 'scheme' as 'lbScheme'),
    ).toThrow(
      "NetworkAndCompute.IaaS.AwsLb declares no parameter 'scheme' (declared: lbScheme, lbType, region).",
    );
  });
});

describe('contract values', () => {
  const contract = {
    offerType: 'X.CaaS.Y',
    serviceTypes: [],
    declaredBy: [
      {
        agentId: 'a',
        agentVersion: 'v1',
        contractSchemaVersion: '2.0',
        provider: 'CaaS',
        parameterRules: [],
      },
    ],
    params: {
      name: {
        type: 'string',
        required: false,
        constraints: {pattern: '[a-z]+', minLength: 2, maxLength: 4},
      },
      soft: {type: 'string', required: false, constraints: {pattern: '[a-z]+', level: 'warn'}},
      tier: {type: 'string', required: false, values: ['Basic', 'Premium'], valuesCaseInsensitive: true},
      zones: {type: 'array', required: false, values: ['1', '2']},
      label: {type: 'string', required: false, values: ['x'], valuesLevel: 'warn'},
      count: {type: 'integer', required: false, constraints: {minimum: 1, maximum: 3}},
      ratio: {type: 'number', required: false},
      on: {type: 'boolean', required: false},
      spec: {type: 'object', required: false},
    },
  } as const satisfies OfferContract;

  it.each([
    ['name', 'ab', undefined],
    ['name', 'A1', `'name' (value withheld) does not match [a-z]+`],
    ['name', 'a', `'name' (value withheld) is shorter than 2`],
    ['name', 'abcde', `'name' (value withheld) is longer than 4`],
    ['soft', 'A1', undefined],
    ['tier', 'premium', undefined],
    ['tier', 'Gold', `"Gold" is not one of Basic, Premium for 'tier'`],
    ['zones', ['1', '2'], undefined],
    ['zones', ['3'], `(value withheld) is not one of 1, 2 for 'zones'`],
    ['label', 'y', undefined],
    ['count', 2, undefined],
    ['count', 2.5, `2.5 is not the integer 'count' takes`],
    ['count', 0, `'count' 0 is below 1`],
    ['count', 4, `'count' 4 is above 3`],
    ['ratio', 'x', `(value withheld) is not the number 'ratio' takes`],
    ['on', 'true', `(value withheld) is not the boolean 'on' takes`],
    ['spec', [], `(value withheld) is not the object 'spec' takes`],
    ['missing', 1, `X.CaaS.Y declares no 'missing'`],
  ])('%s = %j', (key, value, problem) => {
    expect(contractValueProblem(contract, key, value)).toBe(problem);
  });
});
