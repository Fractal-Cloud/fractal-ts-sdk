/**
 * The offer contract generator: the agents' published parameter contracts in,
 * TypeScript modules out. Pure functions only — reading the snapshot and writing
 * files is `scripts/generate-offer-contracts.mjs`; fetching the snapshot is
 * `scripts/refresh-offer-contracts.mjs`. See docs/offer-contracts.md.
 *
 * Input: `param-contract.json` documents (schema 1.x or 2.x). Output: one module
 * per infrastructure domain, exporting one `as const` contract per offer type.
 * An offer type several agents declare (the self-hosted CaaS offers) is merged
 * into one contract, because the SDK emits ONE component for it and any of
 * those agents may be the one that reconciles it.
 */
import {createHash} from 'node:crypto';

/** Members of a projected parameter the generated contract keeps, in this order. */
const PARAMETER_MEMBERS = [
  'type',
  'required',
  'default',
  'values',
  'valuesCaseInsensitive',
  'valuesLevel',
  'sensitive',
  'aliases',
  'deprecated',
  'derived',
  'constraints',
];

const VALUE_TYPES = new Set([
  'string',
  'integer',
  'number',
  'boolean',
  'array',
  'object',
]);

/** Older type spellings, normalized to the contract vocabulary. */
const TYPE_SPELLINGS = {map: 'object', list: 'array', int: 'integer'};

const GENERATED_HEADER =
  '// GENERATED by scripts/generate-offer-contracts.mjs from contracts/snapshot.\n' +
  '// Do not edit: refresh the snapshot (npm run contracts:refresh) and regenerate\n' +
  '// (npm run contracts:generate). See docs/offer-contracts.md.\n';

/** JSON with every object's keys sorted, arrays in order: one text per document. */
export const canonicalJson = value =>
  `${JSON.stringify(sortKeys(value), null, 2)}\n`;

const sortKeys = value => {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(k => [k, sortKeys(value[k])]),
    );
  }
  return value;
};

export const sha256 = text => createHash('sha256').update(text).digest('hex');

const fail = message => {
  throw new Error(`offer contracts: ${message}`);
};

const normalizeType = (type, where) => {
  const normalized = TYPE_SPELLINGS[type] ?? type;
  if (!VALUE_TYPES.has(normalized)) {
    fail(`${where} has type '${type}', which is not a contract value type`);
  }
  return normalized;
};

/** Checks the envelope every projection shares and returns its offers. */
const readProjection = projection => {
  const {schemaVersion, agentId, agentVersion, offers} = projection;
  if (!/^[12]\.\d+$/.test(String(schemaVersion))) {
    fail(`${agentId}: unsupported projection schemaVersion '${schemaVersion}'`);
  }
  if (typeof agentId !== 'string' || typeof agentVersion !== 'string') {
    fail('a projection without agentId or agentVersion');
  }
  if (!Array.isArray(offers)) {
    fail(`${agentId}: offers is not a list`);
  }
  return offers;
};

/** One parameter as the generated contract carries it (description kept aside for JSDoc). */
const toParameter = (param, where) => {
  const out = {
    type: normalizeType(param.type, where),
    required: param.required === true,
  };
  for (const member of PARAMETER_MEMBERS.slice(2)) {
    const value = param[member];
    if (value !== undefined && value !== null) {
      out[member] = value;
    }
  }
  return out;
};

const sameJson = (a, b) =>
  JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));

/**
 * Two agents declaring one key must agree on what it is. `integer` and `number`
 * meet at `number`; any other disagreement is a defect in a producer, reported
 * rather than guessed at.
 */
const mergeParameter = (offerType, key, current, next) => {
  const merged = {...current};
  if (current.type !== next.type) {
    const numeric = new Set(['integer', 'number']);
    if (!numeric.has(current.type) || !numeric.has(next.type)) {
      fail(
        `${offerType}.${key} is '${current.type}' for ${current.agents.join(', ')} ` +
          `and '${next.type}' for ${next.agents.join(', ')}`,
      );
    }
    merged.type = 'number';
  }
  merged.required = current.required || next.required;
  if (!sameJson(current.default, next.default)) {
    delete merged.default;
  }
  // A value must satisfy every agent that constrains it, so the vocabularies
  // intersect; an agent that declares none accepts anything.
  if (current.values !== undefined && next.values !== undefined) {
    merged.values = current.values.filter(v => next.values.includes(v));
  } else {
    merged.values = current.values ?? next.values;
  }
  if (merged.values === undefined) {
    delete merged.values;
  }
  for (const member of PARAMETER_MEMBERS) {
    if (['type', 'required', 'default', 'values'].includes(member)) {
      continue;
    }
    if (merged[member] === undefined && next[member] !== undefined) {
      merged[member] = next[member];
    }
  }
  merged.description = current.description ?? next.description;
  merged.agents = [...current.agents, ...next.agents];
  return merged;
};

/**
 * Merges every projection into one model: offer type → contract. Deterministic
 * whatever the projection order: agents, offers and keys are sorted.
 */
export const buildModel = projections => {
  const sorted = [...projections].sort((a, b) =>
    a.agentId.localeCompare(b.agentId),
  );
  const offers = new Map();
  for (const projection of sorted) {
    for (const offer of readProjection(projection)) {
      const offerType = offer.offerType;
      if (!/^[A-Za-z]+\.[A-Za-z]+\.[A-Za-z0-9]+$/.test(String(offerType))) {
        fail(`${projection.agentId}: '${offerType}' is not an offer type`);
      }
      const entry = offers.get(offerType) ?? {
        offerType,
        declaredBy: [],
        serviceTypes: new Set(),
        params: new Map(),
      };
      if (entry.declaredBy.some(d => d.agentId === projection.agentId)) {
        fail(`${projection.agentId} declares ${offerType} twice`);
      }
      entry.declaredBy.push({
        agentId: projection.agentId,
        agentVersion: projection.agentVersion,
        contractSchemaVersion: String(projection.schemaVersion),
        provider: offer.provider,
        ...(offer.aliasOfOfferType ? {aliasOf: offer.aliasOfOfferType} : {}),
        parameterRules: offer.parameterRules ?? [],
      });
      for (const serviceType of offer.serviceTypes ?? []) {
        entry.serviceTypes.add(serviceType);
      }
      for (const param of offer.params ?? []) {
        const where = `${projection.agentId} ${offerType}.${param.key}`;
        const next = {
          ...toParameter(param, where),
          description: param.description,
          agents: [projection.agentId],
        };
        const current = entry.params.get(param.key);
        entry.params.set(
          param.key,
          current === undefined
            ? next
            : mergeParameter(offerType, param.key, current, next),
        );
      }
      offers.set(offerType, entry);
    }
  }
  return [...offers.values()].sort((a, b) =>
    a.offerType.localeCompare(b.offerType),
  );
};

/** `NetworkAndCompute.IaaS.AwsLb` → `NetworkAndCompute_IaaS_AwsLb`. */
export const contractIdentifier = offerType => offerType.replace(/\./g, '_');

/** `NetworkAndCompute` → `network_and_compute`, the generated module's file name. */
export const domainModule = offerType =>
  offerType
    .split('.')[0]
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();

const literal = value => JSON.stringify(value);

const docComment = (text, indent) => {
  const safe = text.replace(/\*\//g, '*\\/').trim();
  return `${indent}/** ${safe.split('\n').join(`\n${indent} * `)} */\n`;
};

const renderParameter = (key, param, allAgents) => {
  const indent = '    ';
  const {description, agents, ...members} = param;
  const parts = Object.entries(members).map(
    ([member, value]) => `${member}: ${literal(value)}`,
  );
  // Recorded only when not every declaring agent reads the key.
  if (agents.length !== allAgents.length) {
    parts.push(`agents: ${literal(agents)}`);
  }
  const doc = description ? docComment(description, indent) : '';
  return `${doc}${indent}${literal(key)}: {${parts.join(', ')}},\n`;
};

const renderContract = offer => {
  const allAgents = offer.declaredBy.map(d => d.agentId);
  const params = [...offer.params.entries()].sort(([a], [b]) =>
    a.localeCompare(b),
  );
  const declaredBy = offer.declaredBy.map(d => `    ${literal(d)},\n`).join('');
  return (
    `export const ${contractIdentifier(offer.offerType)} = {\n` +
    `  offerType: ${literal(offer.offerType)},\n` +
    `  serviceTypes: ${literal([...offer.serviceTypes].sort())},\n` +
    `  declaredBy: [\n${declaredBy}  ],\n` +
    `  params: {\n${params.map(([k, p]) => renderParameter(k, p, allAgents)).join('')}  },\n` +
    '} as const satisfies OfferContract;\n'
  );
};

/**
 * Renders the model into source texts keyed by module file name. The texts are
 * not yet formatted; `formatModules` runs prettier over them.
 */
export const renderModules = model => {
  const byModule = new Map();
  for (const offer of model) {
    const module = domainModule(offer.offerType);
    byModule.set(module, [...(byModule.get(module) ?? []), offer]);
  }
  const files = new Map();
  for (const [module, offers] of [...byModule.entries()].sort()) {
    files.set(
      `${module}.ts`,
      GENERATED_HEADER +
        "import type {OfferContract} from '../contract/offer_contract';\n\n" +
        offers.map(renderContract).join('\n'),
    );
  }
  return files;
};

/** Formats every module with the repository's prettier settings. */
export const formatModules = async (files, prettier, options) => {
  const formatted = new Map();
  for (const [name, text] of files) {
    formatted.set(
      name,
      await prettier.format(text, {...options, parser: 'typescript'}),
    );
  }
  return formatted;
};
